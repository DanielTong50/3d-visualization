"""Rebuild every shipped scene's derived files, and the demo gallery's index.

    uv run darius gallery            # rewrite them
    uv run darius gallery --check    # CI: fail if anything committed is out of date

For each scene folder: the robotics annotations in scene.json (each object's
inertial and grasps), the robotics bundle (robotics/) and export.zip. Then
scenes/index.json, which the web app reads to list scenes.

The check rebuilds into a temporary copy and compares it with what is committed,
numbers within a relative 1e-4: the files are generated by floating-point code,
and the last digit can differ between machines without anything being stale.
"""

from __future__ import annotations

import io
import json
import math
import re
import shutil
import tempfile
import zipfile
from pathlib import Path

from ..robotics.annotate import annotate
from ..robotics.export import bundle
from ..scene.io import ScenePackage
from ..scene.schema import Scene

SCENES = Path(__file__).resolve().parents[3] / "scenes"

# Scenes first in this order (the web app's hero rotates through them); the rest by name.
# The hand-authored sandbox goes last: it is the simulator's reference scene, not a demo.
ORDER = [
    "kitchen-counter",
    "objectron-mugs",
    "red-cup",
    "dress-shoe",
    "coffee-mug",
    "dslr-camera",
    "paperback",
    "cereal-box",
    "book-on-cloth",
    "standing-book",
]
LAST = ["sandbox"]

DESCRIPTIONS = {
    "kitchen-counter": "Five objects on a kitchen counter, each separated, weighed and simulated.",
    "objectron-mugs": "Two ceramic mugs on a garden table, from a 7-second phone clip.",
    "red-cup": "A light plastic party cup on a wooden floor.",
    "dress-shoe": "A leather dress shoe on a blue cushion.",
    "coffee-mug": "A ceramic coffee mug on a grey tabletop.",
    "dslr-camera": "A DSLR camera body on a yellow cloth.",
    "paperback": "A paperback lying on a floral quilt.",
    "cereal-box": "A box of baby cereal on dark tiles.",
    "book-on-cloth": "A paperback on a patterned cloth.",
    "standing-book": "A thick book standing upright on a wooden desk.",
    "sandbox": "The hand-built reference scene the simulator is tested against: a book, a tissue box, a mug, "
    "a rubber ball and a doorstop, one of each collider type.",
}

NUMBER = re.compile(r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?")


def listing(scene_dir: Path) -> dict:
    scene = Scene.model_validate_json((scene_dir / "scene.json").read_text())
    scanned = scene.provenance is not None
    entry = {
        "id": scene_dir.name,
        "title": scene.title,
        "description": DESCRIPTIONS.get(
            scene_dir.name, f"{len(scene.objects)} objects" + (" scanned from video." if scanned else ".")
        ),
        "kind": "scanned" if scanned else "hand-authored",
        "object_count": len(scene.objects),
        "objects": [o.label for o in scene.objects],
        "thumbnail": "thumbnail.jpg" if (scene_dir / "thumbnail.jpg").exists() else None,
        "export": "export.zip",
    }
    if scanned:
        entry["credit"] = scene.provenance.source + (
            f" ({scene.provenance.license})" if scene.provenance.license else ""
        )
        if scene.provenance.appearance and scene.provenance.appearance.test_psnr_db:
            entry["psnr_db"] = scene.provenance.appearance.test_psnr_db
    return entry


def scene_dirs(root: Path) -> list[Path]:
    def rank(scene_dir: Path) -> tuple[int, int, str]:
        name = scene_dir.name
        if name in LAST:
            return (2, LAST.index(name), name)
        return (0, ORDER.index(name), name) if name in ORDER else (1, 0, name)

    return sorted((p.parent for p in root.glob("*/scene.json")), key=rank)


def rebuild(root: Path) -> list[Path]:
    dirs = scene_dirs(root)
    for scene_dir in dirs:
        package = ScenePackage.load(scene_dir)
        package.manifest = annotate(package)
        package.save()
        bundle.export(scene_dir)
    (root / "index.json").write_text(json.dumps([listing(d) for d in dirs], indent=2) + "\n")
    return dirs


def same_text(a: str, b: str, rel: float = 1e-4, tolerance: float = 1e-6) -> bool:
    """Equal apart from numbers, which may differ by `rel` (relative) or `tolerance` (absolute)."""
    if NUMBER.split(a) != NUMBER.split(b):
        return False
    x, y = NUMBER.findall(a), NUMBER.findall(b)
    return len(x) == len(y) and all(
        math.isclose(float(p), float(q), rel_tol=rel, abs_tol=tolerance) for p, q in zip(x, y, strict=True)
    )


def same_file(a: bytes, b: bytes, name: str) -> bool:
    if a == b:
        return True
    if name.endswith(".zip"):
        with zipfile.ZipFile(io.BytesIO(a)) as za, zipfile.ZipFile(io.BytesIO(b)) as zb:
            if za.namelist() != zb.namelist():
                return False
            return all(same_file(za.read(n), zb.read(n), n) for n in za.namelist())
    try:
        return same_text(a.decode(), b.decode())
    except UnicodeDecodeError:
        return False


def generated(root: Path) -> list[Path]:
    files = [root / "index.json"]
    for scene_dir in scene_dirs(root):
        files += [scene_dir / "scene.json", scene_dir / "export.zip"]
        files += sorted(p for p in (scene_dir / bundle.FOLDER).rglob("*") if p.is_file())
    return files


def stale_files(root: Path) -> list[str]:
    """Files under `root` that a rebuild would change."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "scenes"
        shutil.copytree(root, copy)
        rebuild(copy)
        expected = {p.relative_to(copy) for p in generated(copy)}
        actual = {p.relative_to(root) for p in generated(root)}
        stale = sorted(str(p) for p in expected ^ actual)
        for relative in sorted(expected & actual):
            if not same_file((root / relative).read_bytes(), (copy / relative).read_bytes(), relative.name):
                stale.append(str(relative))
    return stale


def main(check: bool = False, root: Path = SCENES) -> int:
    if check:
        stale = stale_files(root)
        for path in stale:
            print(f"out of date: scenes/{path}")
        if stale:
            print("Run `uv run darius gallery` and commit the result.")
        return 1 if stale else 0
    dirs = rebuild(root)
    print(f"{len(dirs)} scenes -> {root / 'index.json'}")
    return 0
